#!/usr/bin/env python3
"""Smoke-evaluate synthetic table Braille → Chinese translation.

1. Load data/synthetic_tables/tables.jsonl
2. Call package translate(flat_braille) (scaffold stub is OK)
3. Optionally try mT5-small on up to 3 short cell strings (CPU, best-effort)
4. Write data/synthetic_tables/eval_smoke_report.md

Does not fail the build if Hugging Face download/inference is unavailable.
"""

from __future__ import annotations

import json
import os
import sys
import time
import traceback
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "synthetic_tables"
JSONL = DATA / "tables.jsonl"
REPORT = DATA / "eval_smoke_report.md"

sys.path.insert(0, str(ROOT / "src"))

from chinese_braille_toolkit import translate  # noqa: E402


def load_tables() -> list[dict]:
    tables = []
    for line in JSONL.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line:
            tables.append(json.loads(line))
    return tables


def pick_short_cells(tables: list[dict], limit: int = 3) -> list[tuple[str, str, str]]:
    """Return (table_id, zh, braille) for short non-numeric cells."""
    picked: list[tuple[str, str, str]] = []
    for t in tables:
        for row in t["cells"]:
            for cell in row:
                zh = cell["zh"]
                br = cell["braille"]
                if zh.isdigit():
                    continue
                if len(br) > 40:
                    continue
                picked.append((t["id"], zh, br))
                if len(picked) >= limit:
                    return picked
    return picked


def try_mt5(samples: list[tuple[str, str, str]]) -> dict:
    """Best-effort mT5 inference; never raises out of this function."""
    result: dict = {
        "attempted": False,
        "ran": False,
        "deferred_reason": None,
        "outputs": [],
        "error": None,
        "elapsed_s": None,
    }
    if os.environ.get("SKIP_MT5", "").strip() in {"1", "true", "yes"}:
        result["deferred_reason"] = "SKIP_MT5=1 set by environment"
        return result

    result["attempted"] = True
    t0 = time.time()
    try:
        import torch  # noqa: F401
        from transformers import AutoModelForSeq2SeqLM, AutoTokenizer
    except Exception as exc:  # pragma: no cover - env dependent
        result["deferred_reason"] = (
            f"transformers/torch not importable ({type(exc).__name__}: {exc}). "
            "Install optional extras: pip install -e '.[mt5]'"
        )
        return result

    model_id = "Violet-yo/mt5-small-ft-Chinese-Braille"
    try:
        # Keep footprint small: CPU, no device_map auto.
        tokenizer = AutoTokenizer.from_pretrained(model_id)
        model = AutoModelForSeq2SeqLM.from_pretrained(model_id)
        model.eval()
        outs = []
        for tid, zh, br in samples:
            inputs = tokenizer(br, return_tensors="pt", truncation=True, max_length=64)
            with torch.no_grad():
                gen = model.generate(**inputs, max_new_tokens=32)
            pred = tokenizer.decode(gen[0], skip_special_tokens=True)
            outs.append({"table_id": tid, "ref_zh": zh, "braille": br, "pred": pred})
        result["outputs"] = outs
        result["ran"] = True
        result["elapsed_s"] = round(time.time() - t0, 1)
    except Exception as exc:  # download / OOM / network
        result["deferred_reason"] = (
            f"mT5 load/infer failed ({type(exc).__name__}: {exc}). "
            "Model eval deferred; synthetic data still ready."
        )
        result["error"] = traceback.format_exc(limit=5)
        result["elapsed_s"] = round(time.time() - t0, 1)
    return result


def cer(ref: str, hyp: str) -> float | None:
    """Simple Levenshtein CER; None if either empty."""
    if not ref:
        return None
    # Wagner-Fischer
    n, m = len(ref), len(hyp)
    dp = list(range(m + 1))
    for i in range(1, n + 1):
        prev, dp = dp, [i] + [0] * m
        for j in range(1, m + 1):
            cost = 0 if ref[i - 1] == hyp[j - 1] else 1
            dp[j] = min(dp[j - 1] + 1, prev[j] + 1, prev[j - 1] + cost)
    return dp[m] / n


def write_report(tables: list[dict], stub_rows: list[dict], mt5: dict) -> None:
    n_tables = len(tables)
    n_cells = sum(len(row) for t in tables for row in t["cells"])
    tone = {"none": 0, "partial": 0, "full": 0}
    for t in tables:
        for row in t["cells"]:
            for c in row:
                tone[c["tone"]] = tone.get(c["tone"], 0) + 1

    sample = tables[0]
    lines = [
        "# Synthetic table smoke evaluation report",
        "",
        f"Generated by `scripts/eval_table_smoke.py`.",
        "",
        "## Data stats",
        "",
        f"- Tables: **{n_tables}**",
        f"- Cells: **{n_cells}**",
        f"- Tone labels: none={tone.get('none', 0)}, "
        f"partial={tone.get('partial', 0)}, full={tone.get('full', 0)}",
        f"- Source: `{JSONL.relative_to(ROOT)}`",
        "",
        "### Sample table preview (`t01`)",
        "",
        f"- Title: {sample['title_zh']}",
        f"- flat_zh: `{sample['flat_zh']}`",
        f"- flat_braille (truncated): `{sample['flat_braille'][:200]}…`",
        "",
        "## Package stub `translate()`",
        "",
        "Current backend is scaffold (no weights). Outputs below are placeholders.",
        "",
        "| id | flat_zh (trunc) | stub output (trunc) |",
        "|----|-----------------|---------------------|",
    ]
    for row in stub_rows:
        zh = row["flat_zh"][:40].replace("|", "\\|")
        out = row["stub"][:60].replace("|", "\\|")
        lines.append(f"| {row['id']} | `{zh}` | `{out}` |")

    lines += ["", "## mT5-small optional pass", ""]
    if mt5.get("ran"):
        lines.append(
            f"Ran on CPU for {len(mt5['outputs'])} short cells "
            f"in {mt5.get('elapsed_s')}s "
            f"(model `Violet-yo/mt5-small-ft-Chinese-Braille`)."
        )
        lines += [
            "",
            "| table | ref_zh | braille | pred | CER |",
            "|-------|--------|---------|------|-----|",
        ]
        for o in mt5["outputs"]:
            c = cer(o["ref_zh"], o["pred"])
            c_s = f"{c:.2f}" if c is not None else "n/a"
            br = o["braille"][:40].replace("|", "\\|")
            lines.append(
                f"| {o['table_id']} | {o['ref_zh']} | `{br}` | {o['pred']} | {c_s} |"
            )
    else:
        reason = mt5.get("deferred_reason") or "unknown"
        lines.append(f"**Deferred:** {reason}")
        lines.append("")
        lines.append(
            "Honest status: **data ready, model eval deferred**. "
            "Re-run with `pip install -e '.[mt5]'` and network access when ready."
        )
        if mt5.get("error"):
            lines += ["", "<details><summary>traceback</summary>", "", "```", mt5["error"], "```", "", "</details>"]

    lines += [
        "",
        "## Notes",
        "",
        "- Stub predictions are not scored with CER (not real Chinese output).",
        "- Table layout is row-major text only; chart OCR is out of scope here.",
        "- Synthetic Braille ≈ pypinyin GF0019-ish; not embosser QA.",
        "",
    ]
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {REPORT}")


def main() -> None:
    if not JSONL.is_file():
        raise SystemExit(f"Missing {JSONL}; run scripts/build_synthetic_tables.py first")
    tables = load_tables()
    stub_rows = []
    for t in tables:
        stub = translate(t["flat_braille"], backend="mt5")
        stub_rows.append({"id": t["id"], "flat_zh": t["flat_zh"], "stub": stub})

    samples = pick_short_cells(tables, limit=3)
    mt5 = try_mt5(samples)
    write_report(tables, stub_rows, mt5)
    print(
        f"tables={len(tables)} stub_ok={len(stub_rows)} "
        f"mt5_ran={mt5.get('ran')} deferred={mt5.get('deferred_reason')!r}"
    )


if __name__ == "__main__":
    main()
